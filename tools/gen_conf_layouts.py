#!/usr/bin/env python3
"""Generates src/VescConfLayouts.cpp from the VESC firmware's confgenerator.c.

The VESC sends and accepts its motor (mcconf) and app (appconf) configurations as one packed blob whose
layout changes with each firmware release; the first 4 bytes are a signature that names the layout. This
script reads the serialize functions of each listed release and writes a table of fields (name, encoding,
scale) per signature, so VescConfig can find and change single fields in a blob read from the VESC.

Run it again (python3 tools/gen_conf_layouts.py) to add a firmware release to REFS.
"""
import os
import re
import sys
import urllib.request

# Git refs of vedderb/bldc. Release branches hold the final build of each release.
REFS = [
    "5.01",
    "5.02",
    "release_5_03",
    "release_6_00",
    "release_6_02",
    "release_6_05",
    "release_6_06",
    "release_7_00",
]

RAW = "https://raw.githubusercontent.com/vedderb/bldc/{ref}/{path}"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "VescConfLayouts.cpp")


def fetch(ref, path):
    with urllib.request.urlopen(RAW.format(ref=ref, path=path), timeout=30) as response:
        return response.read().decode()


def function_body(source, name):
    match = re.search(r"int32_t\s+" + name + r"\s*\([^)]*\)\s*\{(.*?)\n\}", source, re.S)
    if not match:
        raise SystemExit(f"{name} not found")
    return match.group(1)


FIELD = r"conf->([A-Za-z0-9_.\[\]]+)"
PATTERNS = [
    (re.compile(r"buffer\[ind\+\+\]\s*=\s*(?:\(\w+\))?\s*" + FIELD + r"\s*;"), "U8", None),
    (re.compile(r"buffer_append_uint16\(buffer,\s*" + FIELD + r",\s*&ind\);"), "U16", None),
    (re.compile(r"buffer_append_int16\(buffer,\s*" + FIELD + r",\s*&ind\);"), "I16", None),
    (re.compile(r"buffer_append_uint32\(buffer,\s*" + FIELD + r",\s*&ind\);"), "U32", None),
    (re.compile(r"buffer_append_int32\(buffer,\s*" + FIELD + r",\s*&ind\);"), "I32", None),
    (re.compile(r"buffer_append_float32_auto\(buffer,\s*" + FIELD + r",\s*&ind\);"), "F32_AUTO", None),
    (re.compile(r"buffer_append_float16\(buffer,\s*" + FIELD + r",\s*([0-9.]+),\s*&ind\);"), "F16", "scale"),
    (re.compile(r"buffer_append_float32\(buffer,\s*" + FIELD + r",\s*([0-9.]+),\s*&ind\);"), "F32", "scale"),
]


def parse_fields(body, signature_name):
    fields = []
    for raw_line in body.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("//") or line in ("int32_t ind = 0;", "return ind;"):
            continue
        if signature_name in line:
            continue
        for pattern, kind, extra in PATTERNS:
            match = pattern.fullmatch(line)
            if match:
                scale = float(match.group(2)) if extra else 0.0
                fields.append((match.group(1), kind, scale))
                break
        else:
            raise SystemExit(f"Unrecognised serializer line: {line}")
    return fields


def signatures(header):
    values = {}
    for name in ("MCCONF_SIGNATURE", "APPCONF_SIGNATURE"):
        match = re.search(r"#define\s+" + name + r"\s+(\d+)", header)
        if not match:
            raise SystemExit(f"{name} not found")
        values[name] = int(match.group(1))
    return values


def fw_version(ref):
    try:
        header = fetch(ref, "conf_general.h")
    except Exception:
        return ref
    major = re.search(r"#define\s+FW_VERSION_MAJOR\s+(\d+)", header)
    minor = re.search(r"#define\s+FW_VERSION_MINOR\s+(\d+)", header)
    return f"{int(major.group(1))}.{minor.group(1)}" if major and minor else ref


def main():
    layouts = {}  # (kind, signature) -> (version, fields)
    for ref in REFS:
        print(f"Reading {ref}", file=sys.stderr)
        source = fetch(ref, "confgenerator.c")
        sigs = signatures(fetch(ref, "confgenerator.h"))
        version = fw_version(ref)
        for kind, function, sig_name in (
            ("MCCONF", "confgenerator_serialize_mcconf", "MCCONF_SIGNATURE"),
            ("APPCONF", "confgenerator_serialize_appconf", "APPCONF_SIGNATURE"),
        ):
            fields = parse_fields(function_body(source, function), sig_name)
            key = (kind, sigs[sig_name])
            if key in layouts:
                if layouts[key][1] != fields:
                    raise SystemExit(f"{kind} signature {key[1]} has two layouts")
                if version not in layouts[key][0]:
                    layouts[key][0].append(version)
                continue
            layouts[key] = ([version], fields)

    out = [
        "// Generated by tools/gen_conf_layouts.py from vedderb/bldc confgenerator.c. Do not edit.",
        '#include "VescConfig.h"',
        "",
        "namespace {",
        "using T = VescConfType;",
    ]
    table_names = []
    for index, ((kind, signature), (versions, fields)) in enumerate(layouts.items()):
        version = "/".join(versions)
        name = f"k{kind.title()}{index}"
        table_names.append((name, kind, signature, version, len(fields)))
        out.append(f"// {kind} for firmware {version}")
        out.append(f"const VescConfField {name}[] = {{")
        for field, encoding, scale in fields:
            out.append(f'    {{"{field}", T::{encoding}, {float(scale)!r}f}},')
        out.append("};")
    out.append("}  // namespace")
    out.append("")
    out.append("const VescConfLayout kVescConfLayouts[] = {")
    for name, kind, signature, version, count in table_names:
        out.append(f'    {{VescConfKind::{kind}, {signature}u, "{version}", {name}, {count}}},')
    out.append("};")
    out.append("const size_t kVescConfLayoutCount = sizeof(kVescConfLayouts) / sizeof(kVescConfLayouts[0]);")
    out.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"Wrote {len(layouts)} layouts to {os.path.normpath(OUT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
